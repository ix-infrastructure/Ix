/**
 * Language-list parity gate (#969).
 *
 * The supported languages were written out by hand in the README, CLAUDE.md
 * and the docs site, and those copies drifted from the parser. This script
 * makes `SupportedLanguages` in core-ingestion/src/languages.ts the only
 * source:
 *
 *   - code languages  = enum members with a tree-sitter grammar
 *   - data formats    = enum members in HAND_PARSERS (core-ingestion/src/index.ts)
 *
 * and checks every documented copy against it:
 *
 *   - the code-language table on the docs page and the code-language and
 *     format lists in the README sit between `<!-- languages:… -->` markers
 *     and are regenerated by `--write`;
 *   - every "N languages" count in the README, CLAUDE.md and the docs pages
 *     must equal the number of code languages (`--write` fixes them too);
 *   - the docs page's "Config and data formats" table is hand-written (it says
 *     what each format yields), so it is checked, not generated: its rows must
 *     name exactly the hand-parsed formats.
 *
 * Both source files are read as text, so this needs no build. Run from ix-cli:
 *
 *   node scripts/check-language-docs.mjs          # check; exit 1 on drift
 *   node scripts/check-language-docs.mjs --write  # regenerate, then check
 *
 * check-language-docs.test.mjs runs the check against this repository as part
 * of `npm run test:unit`, so a new enum member without a doc update fails CI.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = join(here, "..", "..");

/** Repo-relative paths this script reads or writes. */
export const PATHS = {
  languagesTs: "core-ingestion/src/languages.ts",
  indexTs: "core-ingestion/src/index.ts",
  languagesDoc: "docs-site/src/content/docs/reference/languages.md",
  readme: "README.md",
  claude: "CLAUDE.md",
  howItWorks: "docs-site/src/content/docs/concepts/how-it-works.md",
};

/** Files whose "N languages" counts must match the code-language count. */
const COUNT_FILES = ["readme", "claude", "howItWorks", "languagesDoc"];

/**
 * How each `SupportedLanguages` value is written in the docs. A new enum
 * member must get a label here; the check names the member until it does.
 */
export const LABELS = {
  javascript: "JavaScript",
  typescript: "TypeScript",
  python: "Python",
  java: "Java",
  c: "C",
  cpp: "C++",
  csharp: "C#",
  go: "Go",
  ruby: "Ruby",
  rust: "Rust",
  php: "PHP",
  kotlin: "Kotlin",
  swift: "Swift",
  scala: "Scala",
  yaml: "YAML",
  dockerfile: "Dockerfile",
  sql: "SQL",
  json: "JSON",
  toml: "TOML",
  markdown: "Markdown",
  r: "R",
  sas: "SAS",
  elixir: "Elixir",
  makefile: "Makefile",
  lua: "Lua",
  bash: "Bash",
  powershell: "PowerShell",
  haskell: "Haskell",
  zig: "Zig",
  html: "HTML",
  xml: "XML",
  hcl: "HCL / Terraform",
  css: "CSS",
  latex: "LaTeX",
  proto: "Protocol Buffers",
};

/**
 * Enum members in declaration order, from the text of languages.ts:
 * `[{ member: "CPlusPlus", value: "cpp" }, ...]`.
 */
export function parseEnum(languagesTs) {
  const start = languagesTs.indexOf("export enum SupportedLanguages");
  if (start < 0) throw new Error("SupportedLanguages enum not found in languages.ts");
  const body = languagesTs.slice(start, languagesTs.indexOf("\n}", start));
  return [...body.matchAll(/^\s*(\w+)\s*=\s*'([^']+)'/gm)].map((m) => ({
    member: m[1],
    value: m[2],
  }));
}

/** Enum member names listed in HAND_PARSERS, from the text of index.ts. */
export function parseHandParsers(indexTs) {
  const start = indexTs.indexOf("const HAND_PARSERS");
  if (start < 0) throw new Error("HAND_PARSERS not found in core-ingestion index.ts");
  const body = indexTs.slice(start, indexTs.indexOf("\n};", start));
  return new Set([...body.matchAll(/\[SupportedLanguages\.(\w+)\]/g)].map((m) => m[1]));
}

/**
 * The two lists, in enum order, plus any member with no label.
 * `{ code: string[], formats: string[], unlabelled: string[] }`
 */
export function languageLists(languagesTs, indexTs) {
  const members = parseEnum(languagesTs);
  const hand = parseHandParsers(indexTs);
  const code = [];
  const formats = [];
  const unlabelled = [];
  for (const { member, value } of members) {
    const label = LABELS[value];
    if (!label) {
      unlabelled.push(`SupportedLanguages.${member} ('${value}')`);
      continue;
    }
    (hand.has(member) ? formats : code).push(label);
  }
  return { code, formats, unlabelled };
}

/** The docs page's code-language table: four labels per row. */
export function renderDocTable(code) {
  const cols = 4;
  const rows = ["| | | | |", "|---|---|---|---|"];
  for (let i = 0; i < code.length; i += cols) {
    const cells = code.slice(i, i + cols);
    while (cells.length < cols) cells.push("");
    rows.push(`| ${cells.join(" | ")} |`.replace(/ {2,}\|/g, " |"));
  }
  return rows.join("\n");
}

/** Backticked labels wrapped to about 80 columns, as the README writes them. */
export function renderTickList(labels) {
  const lines = [];
  let line = "";
  for (const label of labels) {
    const word = `\`${label}\``;
    if (line && line.length + 1 + word.length > 80) {
      lines.push(line);
      line = word;
    } else {
      line = line ? `${line} ${word}` : word;
    }
  }
  if (line) lines.push(line);
  return lines.join("\n");
}

/** Generated blocks: file key -> marker name -> body. */
function generatedBlocks(lists) {
  return {
    languagesDoc: { "languages:code": renderDocTable(lists.code) },
    readme: {
      "languages:code":
        `Symbols, calls and imports are extracted across **${lists.code.length} languages**:\n\n` +
        renderTickList(lists.code),
      "languages:formats": renderTickList(lists.formats),
    },
  };
}

// A block is everything between its start line and its end line; the body
// ends with a newline, so an empty block (start line, end line) still matches.
const markerRe = (name) =>
  new RegExp(`(<!-- ${name}:start[^>]*-->\\n)([\\s\\S]*?)(<!-- ${name}:end -->)`);

// "N languages", including as link text ("[27 languages](/reference/languages/)").
const countMatches = (text) =>
  [...text.matchAll(/\b(\d+) languages\b/g)].map((m) => Number(m[1]));

/** Rows of the "## Config and data formats" table: the bold label in column one. */
export function documentedFormats(languagesDoc) {
  const start = languagesDoc.search(/^## Config and data formats\s*$/m);
  if (start < 0) return null;
  const rest = languagesDoc.slice(start + 1);
  const next = rest.search(/^## /m);
  const section = next < 0 ? rest : rest.slice(0, next);
  return [...section.matchAll(/^\|\s*\*\*([^*]+)\*\*\s*\|/gm)].map((m) => m[1].trim());
}

/**
 * Every way the documented copies differ from the code. `files` maps the keys
 * of PATHS to file text. Returns human-readable problems; empty means parity.
 */
export function collectProblems(files) {
  const lists = languageLists(files.languagesTs, files.indexTs);
  const problems = lists.unlabelled.map(
    (m) => `${m} has no display label: add it to LABELS in ix-cli/scripts/check-language-docs.mjs`,
  );

  for (const [key, blocks] of Object.entries(generatedBlocks(lists))) {
    for (const [name, body] of Object.entries(blocks)) {
      const m = markerRe(name).exec(files[key]);
      if (!m) {
        problems.push(`${PATHS[key]}: missing <!-- ${name}:start --> / <!-- ${name}:end --> block`);
      } else if (m[2] !== `${body}\n`) {
        problems.push(
          `${PATHS[key]}: the ${name} block differs from SupportedLanguages ` +
            "(run node scripts/check-language-docs.mjs --write in ix-cli)",
        );
      }
    }
  }

  for (const key of COUNT_FILES) {
    for (const n of countMatches(files[key])) {
      if (n !== lists.code.length) {
        problems.push(
          `${PATHS[key]}: says "${n} languages", the parser has ${lists.code.length} code languages`,
        );
      }
    }
  }

  const documented = documentedFormats(files.languagesDoc);
  if (documented === null) {
    problems.push(`${PATHS.languagesDoc}: no "## Config and data formats" section`);
  } else {
    const want = new Set(lists.formats);
    const have = new Set(documented);
    for (const f of lists.formats) {
      if (!have.has(f)) problems.push(`${PATHS.languagesDoc}: format table has no row for **${f}**`);
    }
    for (const f of documented) {
      if (!want.has(f)) {
        problems.push(`${PATHS.languagesDoc}: format table row **${f}** is not a hand-parsed format`);
      }
    }
  }
  return problems;
}

/** `files` with every generated block and count brought up to date. */
export function regenerate(files) {
  const lists = languageLists(files.languagesTs, files.indexTs);
  const out = { ...files };
  for (const [key, blocks] of Object.entries(generatedBlocks(lists))) {
    for (const [name, body] of Object.entries(blocks)) {
      out[key] = out[key].replace(markerRe(name), (_, open, _old, close) => `${open}${body}\n${close}`);
    }
  }
  for (const key of COUNT_FILES) {
    out[key] = out[key].replace(/\b\d+ languages\b/g, `${lists.code.length} languages`);
  }
  return out;
}

export function readFiles(root = REPO_ROOT) {
  return Object.fromEntries(
    // .gitattributes checks these out with LF; normalize anyway so a CRLF
    // working copy is compared, not reported as drift.
    Object.entries(PATHS).map(([key, rel]) => [
      key,
      readFileSync(join(root, rel), "utf8").replace(/\r\n/g, "\n"),
    ]),
  );
}

function main() {
  let files = readFiles();
  if (process.argv.includes("--write")) {
    const updated = regenerate(files);
    for (const [key, text] of Object.entries(updated)) {
      if (text !== files[key]) {
        writeFileSync(join(REPO_ROOT, PATHS[key]), text);
        console.log(`check-language-docs: updated ${PATHS[key]}`);
      }
    }
    files = updated;
  }
  const problems = collectProblems(files);
  if (problems.length === 0) {
    const { code, formats } = languageLists(files.languagesTs, files.indexTs);
    console.log(
      `check-language-docs: ${code.length} languages, ${formats.length} formats — docs match SupportedLanguages`,
    );
    process.exit(0);
  }
  for (const p of problems) console.log(p);
  console.log(`check-language-docs: ${problems.length} problem(s)`);
  process.exit(1);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
