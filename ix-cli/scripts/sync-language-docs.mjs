// Read source with the TypeScript parser so this gate needs no dist/ artifacts
// or native grammars. Run from any directory; --check is the default.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";

const repoRoot = fileURLToPath(new URL("../../", import.meta.url));
const start = "<!-- supported-languages:start -->";
const end = "<!-- supported-languages:end -->";
const displayNames = {
  CPlusPlus: "C++",
  CSharp: "C#",
  HCL: "HCL / Terraform",
  Proto: "Protocol Buffers",
};

export function syncLanguageDocs(root = repoRoot, write = false) {
  const source = ts.createSourceFile(
    "languages.ts",
    readFileSync(resolve(root, "core-ingestion/src/languages.ts"), "utf8"),
    ts.ScriptTarget.Latest,
    true,
  );
  const languages = source.statements.find(
    (node) => ts.isEnumDeclaration(node) && node.name.text === "SupportedLanguages",
  );
  if (source.parseDiagnostics.length || !languages?.members.length) {
    throw new Error("Cannot read SupportedLanguages from core-ingestion/src/languages.ts");
  }
  const names = languages.members.map((member) => {
    if (!member.initializer || !ts.isStringLiteral(member.initializer)) {
      throw new Error(`Expected a string language identifier: ${member.name.getText(source)}`);
    }
    const name = member.name.getText(source);
    return displayNames[name] ?? name;
  });
  const rows = [];
  for (let i = 0; i < names.length; i += 4) {
    rows.push(`| ${Array.from({ length: 4 }, (_, j) => names[i + j] ?? "").join(" | ")} |`);
  }
  const table = [
    start,
    "<!-- Generated by ix-cli/scripts/sync-language-docs.mjs; do not edit. -->",
    `Supported languages and formats (**${names.length}**):`,
    "",
    "| | | | |",
    "|---|---|---|---|",
    ...rows,
    end,
  ].join("\n");
  const stale = [];
  for (const path of ["README.md", "docs-site/src/content/docs/reference/languages.md", "CLAUDE.md"]) {
    const fullPath = resolve(root, path);
    const original = readFileSync(fullPath, "utf8");
    // Preserve each document's line endings when comparing and writing.
    const normalized = original.replace(/\r\n/g, "\n");
    let updated;
    if (path === "CLAUDE.md") {
      const row = /^\| `core-ingestion\/` \|.*\|$/gm;
      if ([...normalized.matchAll(row)].length !== 1) {
        throw new Error(`${path}: expected one core-ingestion layout row`);
      }
      updated = normalized.replace(row,
        `| \`core-ingestion/\` | Tree-sitter and text parser/classifier (${names.length} languages and formats) |`);
    } else {
      if (normalized.split(start).length !== 2 || normalized.split(end).length !== 2
          || normalized.indexOf(end) < normalized.indexOf(start)) {
        throw new Error(`${path}: expected one ordered ${start} / ${end} block`);
      }
      updated = normalized.slice(0, normalized.indexOf(start)) + table
        + normalized.slice(normalized.indexOf(end) + end.length);
    }
    if (updated !== normalized) {
      stale.push(path);
      if (write) writeFileSync(fullPath, original.includes("\r\n") ? updated.replace(/\n/g, "\r\n") : updated);
    }
  }
  return stale;
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && !["--write", "--check"].includes(args[0]))) {
    console.error("Usage: node ix-cli/scripts/sync-language-docs.mjs [--check|--write]");
    process.exitCode = 1;
  } else {
    try {
      const stale = syncLanguageDocs(repoRoot, args[0] === "--write");
      if (stale.length && args[0] !== "--write") {
        console.error(`Stale language docs: ${stale.join(", ")}\nRun node ix-cli/scripts/sync-language-docs.mjs --write`);
        process.exitCode = 1;
      } else {
        console.log("Language documentation is in sync with SupportedLanguages.");
      }
    } catch (error) {
      console.error(error.message);
      process.exitCode = 1;
    }
  }
}
