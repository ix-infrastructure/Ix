function parsePositiveIntEnv(name: string, fallback: number): number {
  const raw = process.env[name];
  if (!raw) return fallback;
  const parsed = Number.parseInt(raw, 10);
  return Number.isFinite(parsed) && parsed > 0 ? parsed : fallback;
}

function* walkFiles(
  dir: string,
  recursive: boolean,
): Generator<string> {
  let entries: fs.Dirent[];
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); }
  catch { return; }

  for (const entry of entries) {
    if (entry.isDirectory() && entry.name.startsWith('.') && entry.name !== '.') continue;
    if (IGNORE_DIRS.has(entry.name)) continue;
    const full = nodePath.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (recursive) yield* walkFiles(full, true);
    } else if (entry.isFile()) {
      if (isSupportedSourceFile(entry.name) && !isGeneratedFile(entry.name)) yield full;
    }
  }
}

function canonicalizeDiscoveredFilePath(filePath: string): string {
  try {
    return fs.realpathSync.native(filePath);
  } catch {
    return nodePath.resolve(filePath);
  }
}

/**
 * True when `candidate` lies inside `root`.
 *
 * Both arguments must ALREADY be canonical (realpath'd). This is pure path
 * arithmetic and so cannot see through a symlink itself — resolving first is
 * what gives it meaning, and resolving both sides is what keeps it from
 * rejecting everything when the root is itself reached through a link (macOS
 * `/var` -> `/private/var`, a home on a network mount, a `~/code` symlink).
 */
export function isWithinDiscoveryRoot(root: string, candidate: string): boolean {
  const relative = nodePath.relative(root, candidate);
  // Compare path *segments*: a bare `startsWith('..')` also rejects a
  // legitimate sibling whose name merely begins with dots, e.g. `..shared/`.
  // `isAbsolute` covers Windows, where `relative` across drives is absolute.
  return (
    relative !== '' &&
    relative !== '..' &&
    !relative.startsWith(`..${nodePath.sep}`) &&
    !nodePath.isAbsolute(relative)
  );
}

export function dedupeDiscoveredFilePaths(
  filePaths: string[],
  canonicalize: (filePath: string) => string = canonicalizeDiscoveredFilePath,
): string[] {
  const deduped: string[] = [];
  const seenCanonical = new Set<string>();
  for (const filePath of filePaths) {
    const canonicalPath = canonicalize(filePath);
    if (seenCanonical.has(canonicalPath)) continue;
    seenCanonical.add(canonicalPath);
    deduped.push(canonicalPath);
  }
  return deduped;
}

/**
 * Canonicalize, de-duplicate, and confine discovered paths to `root`.
 *
 * Discovery resolves symlinks, so a repository can name files outside itself:
 * `git ls-files` reports a committed symlink as an ordinary entry and the
 * `statSync` behind it describes the *target*, so `src/notes.ts` ->
 * `~/.ssh/id_rsa` is discovered, read, parsed into the graph and sent to the
 * configured endpoint. `ix ingest --github owner/repo` runs this over
 * repositories nobody has read, which makes repository contents attacker input.
 *
 * (`walkFiles` is not the hole — readdir Dirents describe the link itself, so
 * `isFile()` is false for a symlink and it is skipped there. Git's list is
 * the gap.)
 *
 * A symlink *within* the tree still resolves and is kept, which is what
 * monorepos that link packages around depend on. `root` is `undefined` when a
 * single file was named explicitly: that IS the request, and there is nothing
 * for it to escape from.
 *
 * Kept as one function rather than a filter at the call site so the confinement
 * cannot be dropped without a test noticing.
 */
export function discoverIngestFilePaths(
  discovered: string[],
  root: string | undefined,
  canonicalize: (filePath: string) => string = canonicalizeDiscoveredFilePath,
): { files: string[]; outsideRoot: number } {
  const canonical = dedupeDiscoveredFilePaths(discovered, canonicalize);
  if (root === undefined) return { files: canonical, outsideRoot: 0 };
  // Canonicalize the root too. Comparing a resolved file against an unresolved
  // root drops everything whenever the root is itself reached through a link —
  // macOS `/var` -> `/private/var`, a home on a network mount, a `~/code`
  // symlink — which would look like "this repo has no source files".
  const canonicalRoot = canonicalize(root);
  const files = canonical.filter((candidate) => isWithinDiscoveryRoot(canonicalRoot, candidate));
  return { files, outsideRoot: canonical.length - files.length };
}

/**
 * Exported for the discovery tests: the symlink-containment guarantee is a
 * property of git-listing -> canonicalize -> confine *composed*, and each step
 * looks fine alone. A test that cannot run the real listing cannot show that a
 * committed symlink escapes in the first place.
 */
export function tryGitLsFiles(dir: string, recursive: boolean): string[] | null {
  try {
    const result = spawnSync(
      'git',
      ['ls-files', '--cached', '--others', '--exclude-standard'],
      {
        cwd: dir,
        encoding: 'utf-8',
        maxBuffer: 32 * 1024 * 1024,
      }
    );
    if (result.status !== 0) return null;

    const files: string[] = [];
    const seenCanonical = new Set<string>();
    for (const line of result.stdout.split(/\r?\n/)) {
      if (!line) continue;
      const fullPath = nodePath.resolve(dir, line);
      if (!recursive && nodePath.dirname(fullPath) !== dir) continue;
      if (!isSupportedSourceFile(fullPath)) continue;
      if (isGeneratedFile(nodePath.basename(fullPath))) continue;
      try {
        if (!fs.statSync(fullPath).isFile()) continue;
        const canonicalPath = canonicalizeDiscoveredFilePath(fullPath);
        if (seenCanonical.has(canonicalPath)) continue;
        seenCanonical.add(canonicalPath);
        files.push(canonicalPath);
      } catch {
        // Ignore racy deletes and permission issues during discovery.
      }
    }
    return files;
  } catch {
    return null;
  }
}

function sha256(content: Buffer): string {
  return crypto.createHash('sha256').update(content).digest('hex');
}

function isLikelyMinifiedSource(source: string): boolean {
  if (source.length < MINIFIED_BYTES_THRESHOLD) return false;

  let lineCount = 1;
  let currentLineLength = 0;
  let maxLineLength = 0;
  for (let i = 0; i < source.length; i++) {
    if (source.charCodeAt(i) === 10) {
      lineCount++;
      if (currentLineLength > maxLineLength) maxLineLength = currentLineLength;
      currentLineLength = 0;
    } else {
      currentLineLength++;
    }
  }
  if (currentLineLength > maxLineLength) maxLineLength = currentLineLength;

  const averageLineLength = source.length / Math.max(lineCount, 1);
  return maxLineLength >= MINIFIED_MAX_LINE_THRESHOLD || (lineCount <= 50 && averageLineLength >= MINIFIED_AVG_LINE_THRESHOLD);
}

function stripChunkOps(patch: GraphPatchPayload): GraphPatchPayload {
  return {
    ...patch,
    ops: patch.ops.filter(op => {
      if (op.type === 'UpsertNode' && op['kind'] === 'chunk') return false;
      if (op.type === 'UpsertEdge' && (op['predicate'] === 'CONTAINS_CHUNK' || op['predicate'] === 'NEXT')) return false;
      return true;
    }),
  };
}

/** Strip chunks and claims from patches — mapMode only needs nodes + edges. */
function stripMapModeOps(patch: GraphPatchPayload): GraphPatchPayload {
  return {
    ...patch,
    ops: patch.ops.filter(op => {
      if (op.type === 'AssertClaim' || op.type === 'RetractClaim') return false;
      if (op.type === 'UpsertNode' && op['kind'] === 'chunk') return false;
      if (op.type === 'UpsertEdge' && (op['predicate'] === 'CONTAINS_CHUNK' || op['predicate'] === 'NEXT')) return false;
      return true;
    }),
  };
}

interface StoredPatchEntities {
  nodeIds: string[];
}

function readStoredPatchEntities(raw: unknown): StoredPatchEntities | null {
  const data = (raw as { data?: unknown } | null)?.data as {
    entityIds?: unknown;
    nodeOpCount?: unknown;
    ops?: unknown;
  } | undefined;
  if (!data) return null;
  if (Array.isArray(data.ops)) {
    const ops = data.ops as Array<{ type?: unknown; id?: unknown }>;
    return {
      nodeIds: ops
        .filter(op => op.type === 'UpsertNode' || op.type === 'DeleteNode')
        .map(op => op.id)
        .filter((id): id is string => typeof id === 'string'),
    };
  }
  if (!Array.isArray(data.entityIds)) return null;
  if (!Number.isInteger(data.nodeOpCount)) return null;

  const nodeCount = data.nodeOpCount as number;
  const entityIds = data.entityIds.filter((id): id is string => typeof id === 'string');
  if (nodeCount < 0 || entityIds.length < nodeCount) return null;

  return {
    nodeIds: entityIds.slice(0, nodeCount),
  };
}

async function loadStoredPatchEntities(
  client: Pick<IxClient, 'getPatch'>,
  patchIds: string[],
): Promise<StoredPatchEntities> {
  for (const patchId of patchIds) {
    try {
      const entities = readStoredPatchEntities(await client.getPatch(patchId));
      if (entities) return entities;
      throw new Error(`Patch ${patchId} has no entity manifest`);
    } catch (err) {
      if (!isNotFoundError(err)) throw err;
    }
  }
  throw new Error('Previous source patch was not found');
}

export async function reconcileRemovedEntities(
  client: Pick<IxClient, 'getPatch' | 'entity'>,
  patch: GraphPatchPayload,
  previousPatchIds: string[],
  dependentSourceUris?: Set<string>,
  // `ix map` does not write chunks: stripMapModeOps drops every chunk UpsertNode
  // from the patch. It does NOT drop DeleteNode, and chunk ids hash the chunk's
  // start line, so any edit that shifts lines makes every downstream chunk look
  // removed. Reconciling without this flag therefore had `ix map` after an
  // `ix ingest` delete the file's chunks and never recreate them — the cheaper
  // command silently destroying embedding data the expensive one built. Chunks
  // are not map mode's to reconcile, so in map mode they are left alone.
  mapMode = false,
): Promise<GraphPatchPayload> {
  const previous = await loadStoredPatchEntities(client, previousPatchIds);
  const currentNodeIds = new Set(
    patch.ops
      .filter(op => op.type === 'UpsertNode')
      .map(op => op['id'])
      .filter((id): id is string => typeof id === 'string'),
  );
  const currentEdgeIds = new Set(
    patch.ops
      .filter(op => op.type === 'UpsertEdge')
      .map(op => op['id'])
      .filter((id): id is string => typeof id === 'string'),
  );
  const candidateNodeIds = previous.nodeIds.filter(id => !currentNodeIds.has(id));
  const removedNodeIds: string[] = [];
  const removedEdgeIds = new Set<string>();
  const CHUNK_PREDICATES = new Set(['CONTAINS_CHUNK', 'NEXT']);

  for (const nodeId of candidateNodeIds) {
    try {
      const entity = await client.entity(nodeId);
      // The lookup is already being made for the incident edges, so the kind
      // costs nothing extra. A node whose kind cannot be read (404 — already
      // gone) falls through to the delete, which is a no-op server-side.
      if (mapMode && (entity.node as { kind?: unknown } | undefined)?.kind === 'chunk') {
        continue;
      }
      removedNodeIds.push(nodeId);
      for (const edge of entity.edges ?? []) {
        const edgeRecord = edge as {
          id?: unknown;
          provenance?: { sourceUri?: unknown; source_uri?: unknown };
        };
        const edgeId = edgeRecord.id;
        const predicate = (edge as { predicate?: unknown }).predicate;
        const isChunkEdge = typeof predicate === 'string' && CHUNK_PREDICATES.has(predicate);
        if (typeof edgeId === 'string' && !currentEdgeIds.has(edgeId) && !(mapMode && isChunkEdge)) {
          removedEdgeIds.add(edgeId);
        }
        const sourceUri = edgeRecord.provenance?.sourceUri ?? edgeRecord.provenance?.source_uri;
        if (
          dependentSourceUris &&
          typeof sourceUri === 'string' &&
          sourceUri !== patch.source.uri
        ) {
          dependentSourceUris.add(sourceUri);
        }
      }
    } catch (err) {
      if (!isNotFoundError(err)) throw err;
      // Already absent. Emitting the delete anyway keeps the patch a complete
      // statement of intent and costs nothing.
      removedNodeIds.push(nodeId);
    }
  }

  const nodeOps = patch.ops.filter(op => op.type === 'UpsertNode' || op.type === 'DeleteNode');
  const edgeOps = patch.ops.filter(op => op.type === 'UpsertEdge' || op.type === 'DeleteEdge');
  const otherOps = patch.ops.filter(op =>
    op.type !== 'UpsertNode' && op.type !== 'DeleteNode' &&
    op.type !== 'UpsertEdge' && op.type !== 'DeleteEdge'
  );

  return {
    ...patch,
    ops: [
      ...removedNodeIds.map(id => ({ type: 'DeleteNode', id })),
      ...nodeOps,
      ...[...removedEdgeIds].map(id => ({ type: 'DeleteEdge', id })),
      ...edgeOps,
      ...otherOps,
    ],
  };
}

export function patchRequiresPerFileCommit(patch: GraphPatchPayload): boolean {
  return patch.ops.some(op => op.type === 'DeleteNode' || op.type === 'DeleteEdge');
}

export function planDeletedFileRecovery(
  projectRoot: string,
  filePaths: string[],
  deletedFiles: Map<string, string[]>,
): {
  previousDeletedFiles: Map<string, string[]>;
  nextDeletedFiles: Map<string, string[]>;
  recreatedPaths: string[];
  forceReingestPaths: Set<string>;
} {
  const previousDeletedFiles = new Map<string, string[]>();
  for (const [deletedPath, dependents] of deletedFiles) {
    const absolutePath = nodePath.isAbsolute(deletedPath)
      ? nodePath.resolve(deletedPath)
      : nodePath.resolve(projectRoot, deletedPath);
    previousDeletedFiles.set(absolutePath, dependents);
  }

  const nextDeletedFiles = new Map(previousDeletedFiles);
  const filePathSet = new Set(filePaths.map(filePath => nodePath.resolve(filePath)));
  const recreatedPaths = [...previousDeletedFiles.keys()].filter(filePath =>
    filePathSet.has(filePath)
  );
  const forceReingestPaths = new Set<string>();
  for (const recreatedPath of recreatedPaths) {
    for (const dependent of previousDeletedFiles.get(recreatedPath) ?? []) {
      const absoluteDependent = nodePath.isAbsolute(dependent)
        ? nodePath.resolve(dependent)
        : nodePath.resolve(projectRoot, dependent);
      if (filePathSet.has(absoluteDependent)) forceReingestPaths.add(absoluteDependent);
    }
    nextDeletedFiles.delete(recreatedPath);
  }

  return { previousDeletedFiles, nextDeletedFiles, recreatedPaths, forceReingestPaths };
}

/** Lock contention, as opposed to the transport failures below. Kept separate
  * only so each group's reason for being retryable stays readable. */
const COMMIT_CONFLICT_RETRY_PATTERNS = [
  // ArangoDB lock conflicts. These were briefly split into their own constant
  // so `commitFailureIndictsBackend` could exclude them; that exclusion was
  // reverted in round 3 -- it made the cutoff inert in a real saturation mode --
  // and the split had no consumer left, so it is inlined.
  'write-write conflict',
  'timeout waiting to lock key',
  'error: 1200',
  // Transport-level failures (k8s ingress reset, socket drop under load).
  //
  // These are retried because the request usually never reached the server --
  // but "usually" is the whole of Ix#495. A bulk commit is chunked and writes
  // its idempotency keys as each chunk lands, so a socket that drops after the
  // server started work leaves part of the group committed. Retrying then
  // re-sends a set the server has partly seen, and because the bulk group id is
  // a hash of the patch ids, the retry reproduces the same group and is refused
  // with a 409 that no further retry can clear.
  //
  // The retry stays (it is right far more often than not); what changed is that
  // the resulting 409 is now recoverable — see isBulkPartiallyCommittedError.
  'fetch failed',
  'econnreset',
  'econnrefused',
];

/**
 * A bulk commit the server accepted only in part.
 *
 * Re-sending the same patches cannot fix this: the group id is derived from the
 * patch ids, so an identical retry lands on the identical rejected group. The
 * way through is to commit only what is missing, which the backend tells us by
 * naming the ids that landed (`committed_patch_ids`).
 *
 * Matched on the message because the client throws `${status}: ${body}`, so the
 * JSON body is the tail of the error string.
 */
export function isBulkPartiallyCommittedError(err: unknown): boolean {
  return String(err).toLowerCase().includes('partially committed');
}

/**
 * The patch ids the server says already landed, or undefined when it did not
 * say — a backend older than this field, or a body we cannot parse. Undefined
 * means "fall back", never "nothing landed": treating an unparseable body as an
 * empty set would re-send patches that are already committed.
 */
export function parseBulkCommittedPatchIds(err: unknown): Set<string> | undefined {
  const text = String(err);
  const start = text.indexOf('{');
  const end = text.lastIndexOf('}');
  if (start === -1 || end <= start) return undefined;
  try {
    const body = JSON.parse(text.slice(start, end + 1)) as { committed_patch_ids?: unknown };
    const ids = body.committed_patch_ids;
    if (!Array.isArray(ids)) return undefined;
    const parsed = ids.filter((id): id is string => typeof id === 'string');
    return parsed.length === ids.length ? new Set(parsed) : undefined;
  } catch {
    return undefined;
  }
}

// An abort from the shared wall-clock deadline (or a per-request timeout) must
// NOT be retried — the whole point of the deadline is to stop work. Retrying
// here would defeat it and add 6 more backed-off requests to an already-late
// run. AbortSignal.timeout raises a TimeoutError; an aborted deadline raises an
// AbortError; both also stringify with "aborted".
export function isAbortError(err: unknown): boolean {
  const name = (err as { name?: string } | null)?.name;
  if (name === "AbortError" || name === "TimeoutError") return true;
  return String(err).toLowerCase().includes("aborted");
}

export function isRetryableCommitConflict(err: unknown): boolean {
  if (isAbortError(err)) return false;
  const message = String(err).toLowerCase();
  return COMMIT_CONFLICT_RETRY_PATTERNS.some(pattern => message.includes(pattern));
}

/**
 * Does this commit failure say anything about the BACKEND? (Ix#560)
 *
 * Only failures that indict the backend may feed the run-wide cutoff, because
 * the cutoff abandons every remaining patch in the run.
 *
 * Excluded, and each for its own reason:
 *
 *   - the run's own deadline. That is our wall clock, not the backend's
 *     answer, and `describeCommitOutcome` has a whole branch to keep them
 *     apart. Note this is the DEADLINE, not `isAbortError`: a per-request
 *     `AbortSignal.timeout` also raises TimeoutError, and a backend that
 *     HANGS produces nothing else. Excluding those made the cutoff inert in
 *     exactly the saturation shape it exists for -- a stalled ArangoDB is not
 *     obliged to answer 500, and when it does not, the timeout IS the signal.
 *   - payload-too-large, which is about this patch and not the server; five
 *     oversized generated files in a row must not stop the whole repo.
 *
 * A lock conflict is NOT excluded, though an earlier revision excluded it.
 * `timeout waiting to lock key` and `error: 1200` are what a RocksDB-backed
 * ArangoDB emits under exactly the sustained write contention this cutoff is
 * for, so excluding them made it inert in a real saturation mode -- and, worse,
 * those same patterns are in the RETRY list, so every doomed patch was being
 * multiplied by `retryOnConflict` instead of stopped.
 *
 * The worry that motivated the exclusion -- two overlapping `ix map` runs
 * contending -- is already answered upstream of here: by the time an error
 * reaches this function, `retryOnConflict` has spent six backed-off attempts
 * on it. A conflict that survives all six is not transient contention.
 */
export function commitFailureIndictsBackend(err: unknown, runDeadlineExpired: boolean): boolean {
  if (runDeadlineExpired) return false;
  if (isPayloadTooLargeError(err)) return false;
  return true;
}

async function retryOnConflict<T>(fn: () => Promise<T>, maxRetries: number): Promise<T> {
  for (let attempt = 0; ; attempt++) {
    try {
      return await fn();
    } catch (err) {
      if (attempt >= maxRetries || !isRetryableCommitConflict(err)) throw err;
      // ArangoDB lock conflicts usually clear as soon as the competing transaction
      // commits. Transport errors may need a bit more breathing room under k8s load.
      const delay = 10 * (1 << attempt) + Math.random() * 10;
      await new Promise<void>(r => setTimeout(r, delay));
    }
  }
}

// Every entry here means the same thing operationally: this batch was refused for
// being too big to apply as one unit, so committing fewer patches per request can
// still succeed. That is what makes bisecting the right recovery.
const PAYLOAD_TOO_LARGE_PATTERNS = [
  // A proxy / ingress refused the request body before the backend saw it.
  'payload too large',
  'request entity too large',
  'content too large',
  'request body too large',
  // The backend accepted the body, then ArangoDB refused the write: a bulk commit
  // runs as ONE exclusive transaction, and Arango caps a transaction at 512MB by
  // default (error 32, surfaced as a 500 — not a 413):
  //   "AQL: Maximal transaction size limit of 536870912 bytes is reached"
  // Bisecting splits the group across two transactions, so each half fits.
  // Without this, a big-repo save fell through to the per-file path and a single
  // 1,000-file chunk became 1,000 serialized commits — Ix#516.
  'maximal transaction size',
];

export function isPayloadTooLargeError(err: unknown): boolean {
  const responseError = err as { status?: unknown; statusCode?: unknown } | null;
  if (responseError?.status === 413 || responseError?.statusCode === 413) return true;

  const message = String(err).toLowerCase();
  if (/^(?:error:\s*)?413(?:\b|:)/.test(message)) return true;
  return PAYLOAD_TOO_LARGE_PATTERNS.some(pattern => message.includes(pattern));
}

export async function commitBulkWithPayloadSplit<T, R>(
  items: T[],
  handlers: {
    commitBulk: (batch: T[]) => Promise<R>;
    onBulkCommitted: (batch: T[], result: R) => void;
    commitIndividually: (batch: T[], error: unknown, opts?: { replay?: boolean }) => Promise<void>;
    onSplit?: (batch: T[], error: unknown) => void;
    /** Patch id of an item, so a partly-committed group can be resumed. */
    patchIdOf?: (item: T) => string | undefined;
    onPartialBulk?: (landed: T[], missing: T[], error: unknown) => void;
    /**
     * Has the caller given up on the backend? (Ix#560)
     *
     * Consulted before the per-file fallback, and ONLY there. The bulk is
     * always sent: one request per group is not the amplification, and it is
     * how a backend that recovered mid-run gets to prove it.
     * The fallback exists for a bulk that failed for a
     * reason specific to the GROUP (too large, partly applied), where sending
     * the patches separately is a different request that can succeed. When the
     * backend itself is refusing writes, none of that holds: the fan-out is one
     * doomed request per patch, serialized, against the very backend that is
     * the reason.
     *
     * Absent, nothing is ever abandoned: the behaviour that shipped.
     */
    shouldStop?: () => boolean;
    /** `batch` was abandoned unsent. `error` is absent when none was seen. */
    onAbandoned?: (batch: T[], error?: unknown) => void;
  },
): Promise<void> {
  if (items.length === 0) return;

  // No cutoff check before a bulk that is actually a GROUP. One request per
  // group is not the amplification -- the per-file fallback is, at one request
  // per patch -- and sending it is the only way a backend that has recovered
  // mid-run can prove it and let the rest of the ingest through. Skipping it
  // was strictly worse than useless: the group went to the deferred set and
  // came back as N SERIALIZED per-file commits instead of one bulk.
  //
  // A SINGLE-patch chunk is different, and the difference is the whole issue.
  // At `IX_COMMIT_HTTP_MAX_FILES=1` -- which #560's reporters tried, and which
  // the header's own table measures -- every chunk is one patch, so "one
  // request per group" IS one request per patch and the rule above halves
  // main's cost instead of bounding it: a 10,000-file map against a dead
  // backend still sent ~10,000 doomed bulks. The cutoff applies to those, and
  // recovery is still provable -- the drain's gate lets one probe through every
  // few batches for exactly this.
  if (items.length === 1 && handlers.shouldStop?.()) {
    handlers.onAbandoned?.(items);
    return;
  }

  let result: R;
  try {
    result = await handlers.commitBulk(items);
  } catch (err) {
    if (isPayloadTooLargeError(err) && items.length > 1) {
      handlers.onSplit?.(items, err);
      const midpoint = Math.ceil(items.length / 2);
      await commitBulkWithPayloadSplit(items.slice(0, midpoint), handlers);
      await commitBulkWithPayloadSplit(items.slice(midpoint), handlers);
      return;
    }

    // Part of this group landed. Split it by what the server says it already
    // has: replay the landed ones individually (idempotent no-ops that return
    // their original revision, so the counters and the mtime baseline stay
    // truthful) and re-bulk the rest, which is a different id set and so a
    // different group. Without this the whole batch degrades to the per-file
    // path, which is serialized — hundreds of sequential commits, the several
    // minutes reported in Ix#495.
    const landedIds = isBulkPartiallyCommittedError(err) ? parseBulkCommittedPatchIds(err) : undefined;
    if (landedIds !== undefined && handlers.patchIdOf) {
      const idOf = handlers.patchIdOf;
      const landed = items.filter(item => { const id = idOf(item); return id !== undefined && landedIds.has(id); });
      const missing = items.filter(item => { const id = idOf(item); return id === undefined || !landedIds.has(id); });
      // The server says it already holds every one of them. Re-bulking would
      // repeat this exact call, so this still falls through to the per-file
      // path -- but flagged as a replay, because that is what it is. Without the
      // flag, a tripped breaker counts patches the server has CONFIRMED as
      // commit errors, the same over-reporting `replay` exists to prevent on
      // the sibling branch (Ix#560).
      if (landed.length === items.length && items.length > 0) {
        await handlers.commitIndividually(items, err, { replay: true });
        return;
      }
      // Only worth it when the split is real. If nothing is claimed as landed,
      // re-bulking `missing` would repeat this exact call.
      if (landed.length > 0 && missing.length > 0) {
        handlers.onPartialBulk?.(landed, missing, err);
        // `replay: true` -- the server has confirmed it already holds these.
        // Re-sending them is bookkeeping, not a write the breaker should
        // refuse: skipping them would count patches that DID land as commit
        // errors and drop them from patchesApplied (Ix#495).
        await handlers.commitIndividually(landed, undefined, { replay: true });
        await commitBulkWithPayloadSplit(missing, handlers);
        return;
      }
    }

    if (handlers.shouldStop?.()) {
      handlers.onAbandoned?.(items, err);
      return;
    }
    await handlers.commitIndividually(items, err);
    return;
  }

  handlers.onBulkCommitted(items, result);
}

/**
 * Advance the running max revision, ignoring anything that is not a revision.
 *
 * `result.rev` comes off the wire, and a bare `>` is not safe on it. A string
 * "9" clears `> 0` by coercion and becomes the max; the next comparison is then
 * string-to-string, so `"10" > "9"` is false and the max walks backwards. That
 * value also reaches the user verbatim as the `latestRev` field of
 * `ix ingest --format json`, where every consumer reads it as a number.
 * Screening it here fixes the max, the JSON contract and the persisted baseline
 * in one place, rather than papering over the last of the three.
 */
export function advanceRev(current: number, incoming: unknown): number {
  return isRev(incoming) && incoming > current ? incoming : current;
}

// ---------------------------------------------------------------------------
// Mtime cache — skip readFileSync+sha256 for unchanged files
// ---------------------------------------------------------------------------

export function persistIngestBaselineIfClean(
  projectRoot: string,
  mtimes: Map<string, number>,
  currentRev: number,
  parseErrors: number,
  commitErrors: number,
  now?: Date,
  deletedFiles: Map<string, string[]> = new Map(),
): boolean {
  if (!ingestCompletedCleanly(parseErrors, commitErrors)) return false;
  // An empty mtime map is normally a discovery failure, not an empty repo —
  // an over-broad ignore rule, the wrong cwd, a glob that matched nothing —
  // and persisting it silently discards the baseline, forcing a full re-ingest
  // next run. The original guard rejected every empty map for that reason.
  //
  // But deleting the last mapped file legitimately produces one, and refusing
  // to record that leaves the baseline claiming files that are gone. So the
  // guard now asks *why* the map is empty: with deletions recorded this run,
  // empty is a real state and is persisted; without them, it is still treated
  // as discovery having gone wrong.
  if (mtimes.size === 0 && deletedFiles.size === 0) return false;
  saveIngestBaseline(projectRoot, mtimes, currentRev, now, deletedFiles);
  return true;
}

